export function mariadbSettingDescription(name:unknown,locale:unknown='ko',group:unknown='mariadbd'){
 if(typeof name!=='string'||typeof group!=='string'||!String(locale).toLowerCase().startsWith('ko')||! /^(?:server|mysqld|mariadb|mariadbd)(?:-\d+(?:\.\d+)*)?$/.test(group))return null;
 const key=name.toLowerCase().replaceAll('-','_');
 if(!Object.hasOwn(help,key))return null;
 return {paragraphs:[help[key]],language:'ko',translated:true,commentLabel:'파일의 원본 주석'};
}
