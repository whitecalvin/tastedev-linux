import './build-workspace.ts';
import {verificationWorkRoot} from './verification/work-directory.ts';
import assert from 'node:assert/strict';
import {readFile,writeFile,readdir,mkdir} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {postgresqlSettingDescription} from '../lib/postgresql-setting-description.ts';
import {parsePostgresqlSettings,updatePostgresqlSetting} from '../lib/postgresql-settings-text.ts';
const versions=(await readdir('/usr/lib/postgresql')).filter(value=>/^\d+$/.test(value)).sort((a,b)=>Number(b)-Number(a));
const version=process.argv[2]||versions[0];
assert(version&&/^\d+$/.test(version),'Provide an installed PostgreSQL major version');
const binary=`/usr/lib/postgresql/${version}/bin/postgres`,samplePath=`/usr/share/postgresql/${version}/postgresql.conf.sample`;
const sample=await readFile(samplePath,'utf8'),rows=parsePostgresqlSettings(sample);
const known=new Set(execFileSync(binary,['--describe-config'],{encoding:'utf8'}).split('\n').filter(Boolean).map(line=>line.split('\t')[0].toLowerCase()));
const includes=new Set(['include','include_dir','include_if_exists']);
assert(rows.length>300);
assert(rows.every(row=>row.valid));
assert(rows.every(row=>known.has(row.name.toLowerCase())||includes.has(row.name.toLowerCase())));
assert(rows.every((row,i)=>i===0||row.line>rows[i-1].line));
const row=rows.find(row=>row.name==='shared_buffers');assert(row);
const changed=updatePostgresqlSetting(sample,row,{value:'256MB',enabled:true});
const before=sample.split('\n'),after=changed.split('\n');
assert.equal(before.length,after.length);
assert.deepEqual(before.map((v,i)=>v===after[i]?null:i+1).filter(Boolean),[row.line]);
const edited=parsePostgresqlSettings(changed).find(item=>item.line===row.line);assert(edited);assert.equal(edited.value,'256MB');
const languages=['ko','en','ja','zh','es','fr','de','ru','pt','ar','id','it','ka','pl','sv','tr','uk'];
for(const locale of languages)for(const row of rows){const help=postgresqlSettingDescription(row.name,locale);assert(help.translated&&help.paragraphs.length,`${locale}: ${row.name} missing help`);}
const record={descriptionLanguages:languages,status:'PASS',version:execFileSync(binary,['--version'],{encoding:'utf8'}).trim(),binary,binarySha256:createHash('sha256').update(await readFile(binary)).digest('hex'),samplePath,sampleSha256:createHash('sha256').update(sample).digest('hex'),parsedSettings:rows.length,checks:['all parsed sample entries recognized by matching native server or include syntax','no invalid parsed value','file line order retained','one GUI edit changes only selected line','all sample entries have local descriptions in 17 supported description languages'],systemFilesModified:false,serverStarted:false,databaseConnections:false};
const evidence=path.join(verificationWorkRoot,'postgresql-catalog-native-'+new Date().toISOString().replaceAll(':','-')+'.json');
await mkdir(path.dirname(evidence),{recursive:true,mode:0o700});
await writeFile(evidence,JSON.stringify(record,null,2)+'\n',{mode:0o600});console.log(JSON.stringify({...record,evidence}));
